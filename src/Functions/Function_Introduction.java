package Functions;

public class Function_Introduction {
    static void main() {
        System.out.println("Hello");
        addition();

    }

    public static void addition() {
        int a = 5;
        int b = 6;
        System.out.println(a + b);
        subtraction();
    }

    public static void subtraction() {
        int a = 5;
        int b = 10;
        int c = a - b;
        System.out.println(c);
    }
}
